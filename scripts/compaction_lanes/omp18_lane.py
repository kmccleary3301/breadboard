def remove_fields(raw: bytes, fields: set[str]) -> bytes:
    """Remove top-level JSON members without reserializing retained bytes."""
    text = raw.decode("utf-8")
    decoder = json.JSONDecoder()
    pos = 1
    members = []
    while True:
        start = pos
        while text[pos].isspace():
            pos += 1
        if text[pos] == "}":
            break
        key, end = decoder.raw_decode(text, pos)
        pos = end
        while text[pos].isspace():
            pos += 1
        if text[pos] != ":":
            raise ValueError("Invalid JSON member")
        pos += 1
        while text[pos].isspace():
            pos += 1
        _, end = decoder.raw_decode(text, pos)
        pos = end
        while text[pos].isspace():
            pos += 1
        members.append((key, text[start:pos]))
        if text[pos] == "}":
            break
        if text[pos] != ",":
            raise ValueError("Invalid JSON separator")
        pos += 1
    return ("{" + ",".join(value for key, value in members if key not in fields) + text[pos:]).encode()


def canonical_json(value: Any) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False).encode()


def guarded_summary_fields(stock: dict[str, Any], bb: dict[str, Any], main: dict[str, Any], budget: int | None, deviations: list[str]) -> set[str]:
    fields: set[str] = set()
    if stock.get("tool_choice") == "none":
        # session-handoff.ts uses a side-stream with the live model's tools
        # and output cap. These are equal bytes, not admitted deviations.
        if canonical_json(stock.get("tools")) != canonical_json(main["tools"]) or canonical_json(bb.get("tools")) != canonical_json(main["tools"]):
            raise ValueError("Handoff tools differ from episode tools")
        if type(stock.get("max_completion_tokens")) is not int or type(bb.get("max_completion_tokens")) is not int or stock.get("max_completion_tokens") != main["max_completion_tokens"] or bb.get("max_completion_tokens") != main["max_completion_tokens"]:
            raise ValueError("Handoff token cap differs from live model")
        if bb.get("tool_choice") != "none":
            raise ValueError("Handoff tool_choice differs from stock")
        return fields
    if "compaction_summary_episode_tools" in deviations:
        if "tools" in stock or canonical_json(bb.get("tools")) != canonical_json(main["tools"]):
            raise ValueError("Summary tools differ from admitted values")
        fields.add("tools")
    if "compaction_summary_max_tokens" in deviations:
        if type(budget) is not int or type(stock.get("max_completion_tokens")) is not int or type(bb.get("max_completion_tokens")) is not int or stock.get("max_completion_tokens") != budget or bb.get("max_completion_tokens") != main["max_completion_tokens"]:
            raise ValueError("Summary token cap differs from admitted budget")
        fields.add("max_completion_tokens")
    # tool_choice is stock behavior, not a deviation. Never remove it.
    if stock.get("tool_choice") != bb.get("tool_choice"):
        raise ValueError("Summary tool_choice differs from stock")
    return fields


def normalize_tool_elapsed_time(payload: dict[str, Any]) -> int:
    count = 0
    for message in payload.get("messages", []):
        if message.get("role") == "tool" and isinstance(message.get("content"), str):
            message["content"], substitutions = TOOL_ELAPSED_TIME.subn("Wall time: <elapsed> seconds", message["content"])
            count += substitutions
    return count


def compare_requests(stock: list[Any], bb: list[Any], phases: list[Any], deviations: list[str], used_deviations: set[str] | None = None, timing_substitutions: list[dict[str, int]] | None = None) -> list[Any]:
    diffs = []
    budgets = []
    for phase in phases:
        result = phase["result"]
        if phase["operation"] == "prepare_compaction" and result.get("kind") == "compaction_prepared":
            budgets.extend(result[key].get("max_tokens") for key in ("summary_request", "turn_prefix_request") if result.get(key))
        elif result.get("kind") == "compaction_followup_request":
            budgets.append(result["request"].get("max_tokens"))
    main = bb[0]["json"] if bb else {}
    budget_iter = iter(budgets)
    for i in range(max(len(stock), len(bb))):
        if i >= len(stock) or i >= len(bb):
            diffs.append({"index": i, "type": "request_count"})
            continue
        left = bytes.fromhex(stock[i]["raw_body_bytes"])
        right = bytes.fromhex(bb[i]["raw_body_bytes"])
        if stock[i]["json"].get("tools") is None or stock[i]["json"].get("tool_choice") == "none" or bb[i]["json"].get("tool_choice") == "none":
            budget = next(budget_iter, None)
            try:
                fields = guarded_summary_fields(stock[i]["json"], bb[i]["json"], main, budget, deviations)
                if used_deviations is not None:
                    if "tools" in fields:
                        used_deviations.add("compaction_summary_episode_tools")
                    if "max_completion_tokens" in fields:
                        used_deviations.add("compaction_summary_max_tokens")
                left, right = remove_fields(left, fields), remove_fields(right, fields)
            except ValueError as error:
                diffs.append({"index": i, "type": "deviation_guard", "message": str(error)})
                continue
        left_payload, right_payload = json.loads(left), json.loads(right)
        counts = {"index": i, "stock": normalize_tool_elapsed_time(left_payload),
                  "bb": normalize_tool_elapsed_time(right_payload)}
        if timing_substitutions is not None:
            timing_substitutions.append(counts)
        left = canonical_json(left_payload)
        right = canonical_json(right_payload)
        if left != right:
            offset = next((n for n, (a, b) in enumerate(zip(left, right)) if a != b), min(len(left), len(right)))
            diffs.append({"index": i, "type": "byte_diff", "first_offset": offset,
                "stock_sha256": hashlib.sha256(left).hexdigest(), "bb_sha256": hashlib.sha256(right).hexdigest(),
                "stock_excerpt": left[max(0, offset-40):offset+140].decode(), "bb_excerpt": right[max(0, offset-40):offset+140].decode()})
    return diffs


def run_scenario(out: Path, scenario: str) -> dict[str, Any]:
    out.mkdir(parents=True, exist_ok=True)
    workspace = out / "workspace"
    seed_workspace(workspace)
    stock_server = MockProvider(scenario_script(scenario), out / "stock.requests.jsonl")
    bb_server = MockProvider(scenario_script(scenario), out / "bb.requests.jsonl")
    stock_server.start()
    bb_server.start()
    try:
        stock = run_stock(workspace, out / "stock-runtime", stock_server.base_url + "/v1")
        bb = asyncio.run(run_bb(workspace, out / "bb-runtime", bb_server.base_url + "/v1"))
    finally:
        stock_server.stop()
        bb_server.stop()
    requests = {"stock": stock_server.engine.recorded_requests, "bb": bb_server.engine.recorded_requests}
    policy = yaml.safe_load((TARGET_DIR / "harness.yaml").read_bytes())["policy"]
    deviations = [d["id"] for d in policy["deviations"]]
    controls = policy["execution"]["bounded_controls"]
    compactions = {"stock": sum(e["type"] == "auto_compaction_end" and e["committed"] for e in stock["events"]),
                   "bb": sum(p["result"].get("kind") == "compaction_finalized" for p in bb["phases"])}
    used_deviations: set[str] = set()
    timing_substitutions: list[dict[str, int]] = []
    diffs = compare_requests(requests["stock"], requests["bb"], bb["phases"], deviations, used_deviations, timing_substitutions)
    report = {"target": TARGET_ID, "scenario": scenario, "overrides": {"context_window": {"production": target_config()["context_window"], "lane": WINDOW}},
        "comparison_basis": "canonical JSON, sort_keys=True, separators=(',', ':'), ensure_ascii=False",
        "bounded_controls": controls,
        "admission_transcript_bytes": controls["max_model_calls"] * controls["raw_evidence_bytes_per_outcome"],
        "compaction_count_basis": "successful native auto_compaction_end, including non-skipped shake; BB compaction_finalized",
        "environment_normalization": {"pattern": TOOL_ELAPSED_TIME_PATTERN,
            "scope": "tool-result message content strings only", "substitutions": timing_substitutions},
        "raw_byte_difference_indices": [i for i, (a, b) in enumerate(zip(requests["stock"], requests["bb"]))
                                        if a["raw_body_bytes"] != b["raw_body_bytes"]],
        "request_counts": {side: len(rows) for side, rows in requests.items()}, "compaction_counts": compactions,
        "diffs": diffs,
        "deviations_used": sorted(used_deviations), "deviations_admitted": deviations,
        "stock": stock, "bb": bb, "requests": requests}
    (out / "lane_report.json").write_text(json.dumps(report, indent=2))
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--scenario", choices=SCENARIOS)
    args = parser.parse_args()
    reports = [run_scenario(args.out / scenario, scenario) for scenario in ([args.scenario] if args.scenario else SCENARIOS)]
    print(json.dumps([{k: r[k] for k in ("scenario", "request_counts", "compaction_counts", "diffs", "deviations_used")} for r in reports], indent=2))
    if any(r["diffs"] for r in reports):
        raise SystemExit(1)


if __name__ == "__main__":
    main()
