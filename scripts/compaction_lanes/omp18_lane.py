def target_config() -> dict[str, Any]:
    return json.loads((TARGET_DIR / "native-config.json").read_bytes())


def scenario_script(scenario: str) -> list[dict[str, Any]]:
    if scenario not in SCENARIOS:
        raise ValueError(scenario)
    low = {"input_tokens": 1000, "output_tokens": 30, "total_tokens": 1030}
    high = {"input_tokens": WINDOW - 1000, "output_tokens": 30, "total_tokens": WINDOW - 970}
    def text(value: str, usage: dict[str, int] = low) -> dict[str, Any]:
        return {"type": "text", "text": value, "usage": usage}
    def batch(index: int, size: int = 1) -> dict[str, Any]:
        # Identical tiny filesystem reads race on completion order. Real shell
        # commands with distinct delays make the batch reproducible without
        # modifying either scheduler or sorting any captured message array.
        name = "read" if size == 1 else "bash"
        return {"type": "response", "tool_calls": [
            {"name": name, "call_id": f"{name}-{index}-{i}",
             "arguments": json.dumps({"i": "Reading numbered records", **(
                 {"path": f"records-{index}-{i}.txt"} if size == 1 else
                 {"command": f"sleep {i + 0.4:.2f}; cat records-{index}-{i}.txt"})})}
            for i in range(size)], "usage": low}
    summary = text("## Goal\nInspect records.\n## Progress\nRead records.\n## Next steps\nFinish inspection.")
    if scenario == "final_over_threshold":
        return [batch(0), text("Inspection complete.", high), summary]
    if scenario == "long_session":
        first = batch(1)
        first["usage"] = high
        return [batch(0), first, summary, text("Inspection complete.", high), summary]
    if scenario == "large_tool_batch":
        large = batch(1, 12)
        large["usage"] = high
        return [batch(0, 12), large, summary, text("Inspection complete.")]
    error = {"type": "error", "error": "context_length_exceeded",
             "message": "Your input exceeds the context window of this model.", "status_code": 400}
    # Default overflow dispatch tries source shake before soft summarization.
    return [batch(0, 12), error, text("Inspection complete.")]


def seed_workspace(workspace: Path) -> None:
    workspace.mkdir(parents=True, exist_ok=True)
    for batch in range(4):
        for i in range(12):
            text = "".join(f"record {batch} file {i} item {j}: value {j * 7919}\n" for j in range(240))
            (workspace / f"records-{batch}-{i}.txt").write_text(text)


def run_stock(workspace: Path, scratch: Path, base_url: str) -> dict[str, Any]:
    config = target_config()
    source = Path(os.environ["BB_OMP_TEST_SOURCE_ROOT"])
    version = json.loads((source / "packages/coding-agent/package.json").read_bytes())["version"]
    if version != "18.1.17":
        raise ValueError(f"Wrong stock version: {version}")
    provenance = json.loads((TARGET_DIR / "tool-surface.json").read_bytes())["native_description_provenance"]
    scratch.mkdir(parents=True, exist_ok=True)
    (scratch / "home").mkdir(exist_ok=True)
    payload = {
        "source": str(source), "workspace": str(workspace), "scratch": str(scratch),
        "home": str(scratch / "home"), "prompt": PROMPT, "base_url": base_url,
        "provider": config["model_registry"]["provider_id"], "tools": config["tool_names"],
        "model": {"id": "model-a", "name": "Model A", "reasoning": False, "input": ["text"],
                  "contextWindow": WINDOW, "maxTokens": config["model_max_tokens"]},
        "descriptions": {name: {"original_sha256": provenance["original_sha256"][name],
            "bounded_sha256": provenance["bounded_sha256"][name],
            "removed_spans": provenance["removed_spans"][name]} for name in config["tool_names"]},
    }
    proc = subprocess.run([os.environ["BB_OMP_TEST_BUN"], "-e", STOCK_DRIVER], input=json.dumps(payload),
                          capture_output=True, text=True, cwd=workspace, timeout=120)
    (scratch / "stock.stderr").write_text(proc.stderr)
    if proc.returncode:
        raise RuntimeError(f"Stock SDK failed ({proc.returncode}): {proc.stderr}")
    return json.loads(proc.stdout)


