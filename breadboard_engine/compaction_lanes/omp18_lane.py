def scenario_script(scenario: str) -> list[dict[str, Any]]:
    if scenario not in SCENARIOS:
        raise ValueError(scenario)
    low = {"input_tokens": 1000, "output_tokens": 30, "total_tokens": 1030}
    high = {"input_tokens": WINDOW - 1000, "output_tokens": 30, "total_tokens": WINDOW - 970}
    def text(value: str, usage: dict[str, int] = low) -> dict[str, Any]:
        return {"type": "text", "text": value, "usage": usage}
    def batch(index: int, size: int = 1) -> dict[str, Any]:
        # Identical tiny filesystem reads race on completion order. Real shell
        # commands with distinct delays make the batch reproducible without
        # modifying either scheduler or sorting any captured message array.
        name = "read" if size == 1 else "bash"
        return {"type": "response", "tool_calls": [
            {"name": name, "call_id": f"{name}-{index}-{i}",
             "arguments": json.dumps({"i": "Reading numbered records", **(
                 {"path": f"records-{index}-{i}.txt"} if size == 1 else
                 {"command": f"sleep {i + 0.4:.2f}; cat records-{index}-{i}.txt"})})}
            for i in range(size)], "usage": low}
    summary = text("## Goal\nInspect records.\n## Progress\nRead records.\n## Next steps\nFinish inspection.")
    if scenario == "final_over_threshold":
        return [batch(0), text("Inspection complete.", high), summary]
    if scenario == "long_session":
        first = batch(1)
        first["usage"] = high
        return [batch(0), first, summary, text("Inspection complete.", high), summary]
    if scenario == "large_tool_batch":
        large = batch(1, 12)
        large["usage"] = high
        return [batch(0, 12), large, summary, text("Inspection complete.")]
    error = {"type": "error", "error": "context_length_exceeded",
             "message": "Your input exceeds the context window of this model.", "status_code": 400}
    # Default overflow dispatch tries source shake before soft summarization.
    return [batch(0, 12), error, text("Inspection complete.")]


def seed_workspace(workspace: Path) -> None:
    workspace.mkdir(parents=True, exist_ok=True)
